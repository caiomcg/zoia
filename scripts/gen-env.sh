#!/usr/bin/env bash
#
# Generates a .env with consistent secrets.
#
#   ./scripts/gen-env.sh zoia.example.com sfu.example.com > .env
#   ./scripts/gen-env.sh --homolog zoia-homolog.example.com sfu.example.com \
#     <prod-vm-ip> > .env
#
# --homolog writes the .env for a homolog VM (docs/adr/0035-homolog-environment.md):
# its own session secret, room prefix and LiveKit key, against the production
# SFU. The new key must also be added to production's LIVEKIT_KEYS; the line to
# use is printed to stderr.
#
# The LiveKit credentials appear in three places that must agree: the app reads
# LIVEKIT_API_KEY and LIVEKIT_API_SECRET, and the livekit container reads
# LIVEKIT_KEYS, which is those same two values as "key: secret". Getting them
# out of step produces an authentication failure at connect time with no useful
# error, so they are generated together here rather than by hand.

set -euo pipefail

HOMOLOG=""
if [[ "${1:-}" == "--homolog" ]]; then
  HOMOLOG=1
  shift
fi

APP_HOST="${1:-}"
SFU_HOST="${2:-}"
PROD_IP="${3:-}"

if [[ -z "$APP_HOST" || -z "$SFU_HOST" || ( -n "$HOMOLOG" && -z "$PROD_IP" ) ]]; then
  echo "usage: $0 <app-hostname> <sfu-hostname>" >&2
  echo "       $0 --homolog <app-hostname> <sfu-hostname> <prod-vm-ip>" >&2
  echo "   eg: $0 zoia.example.com sfu.example.com" >&2
  exit 1
fi

api_key="API$(openssl rand -hex 6)"
api_secret="$(openssl rand -base64 36 | tr -d '\n/+=' | head -c 44)"
session_secret="$(openssl rand -base64 48 | tr -d '\n')"
addon_host_secret="$(openssl rand -hex 32)"

if [[ -n "$HOMOLOG" ]]; then
  cat >&2 <<EOF
Add this key to LIVEKIT_KEYS in production's .env, beside the key already
there, as a YAML map (a plain comma-separated list does not parse):

  LIVEKIT_KEYS="{<prod key>: <prod secret>, ${api_key}: ${api_secret}}"

then on the production VM: docker compose up -d livekit
EOF
  cat <<EOF
# Generated by scripts/gen-env.sh --homolog on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# Keep this file on the homolog VM only. It is excluded from git and from deploys.

PUBLIC_HOST=${APP_HOST}
# The production SFU: clients connect to it publicly, the app over the LAN.
LIVEKIT_WS_URL=wss://${SFU_HOST}
LIVEKIT_API_URL=http://${PROD_IP}:7880

# This environment's own key on the production SFU. It must also be in
# production's LIVEKIT_KEYS.
LIVEKIT_API_KEY=${api_key}
LIVEKIT_API_SECRET=${api_secret}

SESSION_SECRET=${session_secret}

MAX_BITRATE=20000000
MAX_FRAMERATE=60
CAPTURE_WIDTH=3840
CAPTURE_HEIGHT=2160
VIDEO_CODEC=vp9

# Every channel's room starts with this, which keeps the homolog's rooms apart
# from production's on the shared SFU.
ROOM_NAME=zoia-homolog
PORT=3000
# One proxy hop: the production caddy in front of this app.
TRUST_PROXY=1
SECURE_COOKIES=true
EOF
  exit 0
fi

cat <<EOF
# Generated by scripts/gen-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# Keep this file on the server only. It is excluded from git and from deploys.

PUBLIC_HOST=${APP_HOST}
SFU_HOST=${SFU_HOST}
LIVEKIT_WS_URL=wss://${SFU_HOST}

# Cloudflare API token scoped to Zone:DNS:Edit on this zone, for the ACME
# DNS-01 challenge. Fill this in by hand — it is not generated.
CLOUDFLARE_API_TOKEN=${CLOUDFLARE_API_TOKEN:-PASTE_YOUR_TOKEN_HERE}

LIVEKIT_API_KEY=${api_key}
LIVEKIT_API_SECRET=${api_secret}
# Same pair, in the format the livekit container expects.
LIVEKIT_KEYS="${api_key}: ${api_secret}"

SESSION_SECRET=${session_secret}

# Addons (docs/adr/0041-addons.md): the addon host runs their containers.
COMPOSE_PROFILES=addons
ADDON_HOST_URL=http://addon-host:3100
ADDON_HOST_SECRET=${addon_host_secret}

# Broadcast quality. Upload needed = MAX_BITRATE x remote viewers.
MAX_BITRATE=20000000
MAX_FRAMERATE=60
CAPTURE_WIDTH=3840
CAPTURE_HEIGHT=2160
VIDEO_CODEC=vp9

ROOM_NAME=zoia
PORT=3000
# One proxy hop: the caddy container in front of the app.
TRUST_PROXY=1
SECURE_COOKIES=true
EOF
